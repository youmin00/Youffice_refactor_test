def build_relationship_context(
    employee_name: str,
    conversation_partner: str | None = None,
    present_employee_names: list[str] | None = None,
    situation: str | None = None,
) -> str:
    """현재 대화에 필요한 관계 맥락만 선택해 프롬프트에 넣습니다.

    발화자와 상대 직원이 지정되지 않은 일반 업무 대화에는 관계 설정을 주입하지
    않아 기존 업무 결과와 프롬프트 길이에 영향을 주지 않습니다.
    """

    candidates: list[str] = []
    if conversation_partner and conversation_partner != employee_name:
        candidates.append(conversation_partner)
    for present_name in present_employee_names or []:
        if present_name != employee_name and present_name not in candidates:
            candidates.append(present_name)

    relationship_lines = []
    for other_name in candidates:
        profile = RELATIONSHIP_PROFILES.get((employee_name, other_name))
        if profile is None:
            profile = RELATIONSHIP_PROFILES.get((other_name, employee_name))
        if profile:
            relationship_lines.append(f"- {other_name}: {profile}")

    if not relationship_lines:
        return ""

    situation_rule = RELATIONSHIP_SITUATION_RULES.get(situation or "")
    context = (
        "현재 대화에 필요한 직원 관계 맥락은 다음과 같다. "
        "관계는 말투와 협업 분위기를 보조할 뿐, 존재하지 않는 사건이나 감정을 만들지 않는다.\n"
        + "\n".join(relationship_lines)
        + "\n"
        + "관계 적용 원칙: 친한 직원끼리도 사실 확인, 기술 판단, 검수 판정, 재작업 여부를 봐주지 않는다. "
        "대화에 필요한 직원만 등장시키고 모든 직원을 억지로 말하게 하지 않는다. "
    )
    if situation_rule:
        context += f"현재 상황({situation}) 원칙: {situation_rule} "
    return context


